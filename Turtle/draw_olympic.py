import turtle

turtle.width(10)
turtle.color("blue")
turtle.circle(50)

turtle.penup()
turtle.goto(100, 0)
turtle.pendown()
turtle.color("black")
turtle.circle(50)

turtle.penup()
turtle.goto(200, 0)
turtle.pendown()
turtle.color("red")
turtle.circle(50)

turtle.penup()
turtle.goto(50, -60)
turtle.pendown()
turtle.color("yellow")
turtle.circle(50)

turtle.penup()
turtle.goto(150, -60)
turtle.pendown()
turtle.color("green")
turtle.circle(50)

turtle.done()